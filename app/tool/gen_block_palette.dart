// Generates lib/core/theme/block_palette.g.dart from
// assets/design/palette.json (docs/03-ux-spec.md §1, plan M1.0).
//
// Run from app/:  dart run tool/gen_block_palette.dart
// test/core/theme/block_palette_test.dart fails when the output is stale.
import 'dart:convert';
import 'dart:io';

const inputPath = 'assets/design/palette.json';
const outputPath = 'lib/core/theme/block_palette.g.dart';

Future<void> main() async {
  final json = jsonDecode(await File(inputPath).readAsString());
  await writeFormatted(renderBlockPalette(json), outputPath);
  stdout.writeln('Wrote $outputPath');
}

/// Writes [source] to [path] and runs `dart format` on it, so the committed
/// file is byte-identical to what CI's format check expects.
Future<void> writeFormatted(String source, String path) async {
  await File(path).writeAsString(source);
  final result = await Process.run('dart', ['format', path]);
  if (result.exitCode != 0) {
    throw ProcessException('dart', ['format', path], '${result.stderr}');
  }
}

/// Renders the `part` file for `block_palette.dart` from decoded palette
/// JSON. Throws [FormatException] on a malformed palette.
String renderBlockPalette(Object? json) {
  final doc = _map(json, 'root');
  final alpha = _map(doc['fillAlpha'], 'fillAlpha');
  final colors = doc['colors'];
  if (colors is! List || colors.isEmpty) {
    throw const FormatException('"colors" must be a non-empty list');
  }
  final entries = [for (final c in colors) _Entry.parse(c)];
  final keys = entries.map((e) => e.key).toList();
  if (keys.toSet().length != keys.length) {
    throw FormatException('duplicate colour keys in $keys');
  }
  final fallback = doc['default'];
  if (fallback is! String || !keys.contains(fallback)) {
    throw FormatException('"default" must be one of $keys');
  }

  return '''
// GENERATED by tool/gen_block_palette.dart from $inputPath.
// Do not edit by hand; edit the JSON and re-run the generator.

part of 'block_palette.dart';

/// User-selectable block colours, in picker order (docs/03-ux-spec.md §1).
///
/// [key] is the persisted `color_key` (docs/05-data-model.md).
enum BlockColor {
  ${keys.join(',\n  ')};

  /// Colour for new tasks and unknown keys; matches the `color_key` column
  /// default.
  static const fallback = BlockColor.$fallback;

  static final _byKey = values.asNameMap();

  /// Persisted `color_key` value.
  String get key => name;

  /// Parses a stored `color_key`, falling back to [fallback] so a key from a
  /// newer app version never breaks rendering.
  static BlockColor fromKey(String? key) => _byKey[key] ?? fallback;
}

const _lightFillAlpha = ${_alpha(alpha, 'light')};
const _darkFillAlpha = ${_alpha(alpha, 'dark')};

${_swatchList('_lightSwatches', entries.map((e) => (e.key, e.light)))}

${_swatchList('_darkSwatches', entries.map((e) => (e.key, e.dark)))}
''';
}

String _swatchList(String name, Iterable<(String, _Swatch)> swatches) {
  final body = swatches.map(
    (s) => '  // ${s.$1}\n'
        '  BlockSwatch(base: ${s.$2.base}, strong: ${s.$2.strong},),',
  );
  return 'const $name = <BlockSwatch>[\n${body.join('\n')}\n];';
}

String _alpha(Map<String, Object?> alpha, String mode) {
  final value = alpha[mode];
  if (value is! num || value <= 0 || value >= 1) {
    throw FormatException('fillAlpha.$mode must be a number in (0, 1)');
  }
  return value.toDouble().toString();
}

Map<String, Object?> _map(Object? value, String where) {
  if (value is Map<String, Object?>) return value;
  throw FormatException('$where must be an object');
}

final _hex = RegExp(r'^#[0-9A-Fa-f]{6}$');
final _key = RegExp(r'^[a-z]+$');

final class _Swatch {
  _Swatch.parse(Object? json, String where)
      : base = _color(_map(json, where)['base'], '$where.base'),
        strong = _color(_map(json, where)['strong'], '$where.strong');

  final String base;
  final String strong;

  static String _color(Object? value, String where) {
    if (value is! String || !_hex.hasMatch(value)) {
      throw FormatException('$where must be "#RRGGBB", got $value');
    }
    return 'Color(0xFF${value.substring(1).toUpperCase()})';
  }
}

final class _Entry {
  _Entry._(this.key, this.light, this.dark);

  factory _Entry.parse(Object? json) {
    final map = _map(json, 'colour');
    final key = map['key'];
    if (key is! String || !_key.hasMatch(key)) {
      throw FormatException('colour key must be lowercase letters, got $key');
    }
    return _Entry._(
      key,
      _Swatch.parse(map['light'], '$key.light'),
      _Swatch.parse(map['dark'], '$key.dark'),
    );
  }

  final String key;
  final _Swatch light;
  final _Swatch dark;
}
