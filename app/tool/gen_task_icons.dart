// Generates the task icon library from assets/design/task_icons.json
// (docs/10-ui-concept-a.md §3 "Icon set", ADR-0012):
//   lib/core/theme/task_icons.gen.dart      the `TaskIcon` enum + categories
//   lib/shared/pickers/task_icon_names.gen.dart  localized names
//   lib/core/l10n/arb/app_*.arb             the `taskIcon*` keys
//
// Run from app/:  dart run tool/gen_task_icons.dart && flutter gen-l10n
// test/core/theme/task_icons_test.dart fails when an output is stale.
import 'dart:convert';
import 'dart:io';

import 'gen_task_palette.dart' show writeFormatted;

export 'gen_task_palette.dart' show writeFormatted;

const inputPath = 'assets/design/task_icons.json';
// Not `.g.dart`: `build_runner build -d` deletes `.g.dart` parts it did not
// generate (CI codegen step).
const enumOutputPath = 'lib/core/theme/task_icons.gen.dart';
const namesOutputPath = 'lib/shared/pickers/task_icon_names.gen.dart';
const languages = ['en', 'de', 'es', 'fr'];
String arbPath(String lang) => 'lib/core/l10n/arb/app_$lang.arb';

const _header =
    '// GENERATED by tool/gen_task_icons.dart from $inputPath.\n'
    '// Do not edit by hand; edit the JSON and re-run the generator.\n';

const _arbDescription =
    'Task icon name (icon picker, icon search, screen readers).';
const _arbCategoryDescription = 'Section title in the task icon picker.';

Future<void> main() async {
  final lib = IconLibrary.parse(
    jsonDecode(await File(inputPath).readAsString()),
  );
  await writeFormatted(renderTaskIcons(lib), enumOutputPath);
  await writeFormatted(renderTaskIconNames(lib), namesOutputPath);
  for (final lang in languages) {
    final file = File(arbPath(lang));
    await file.writeAsString(mergeArb(await file.readAsString(), lib, lang));
  }
  stdout.writeln(
    'Wrote ${lib.icons.length} icons: $enumOutputPath, $namesOutputPath '
    'and the ARB files; now run `flutter gen-l10n`.',
  );
}

/// Renders the `part` file for `task_icons.dart`.
String renderTaskIcons(IconLibrary lib) {
  final cats = lib.categories.map((c) => '  ${c.id}');
  final icons = [
    for (final i in lib.icons)
      "  ${i.id}('${i.key}', TaskIconCategory.${i.category}, "
          "DotGlyph('${i.d}'))",
    "  ${lib.plain.id}('${lib.plain.key}', "
        'TaskIconCategory.${lib.categories.first.id}, null)',
  ];
  final legacy = lib.legacy.entries.map(
    (e) => "  '${e.key}': TaskIcon.${e.value},",
  );
  return '''
$_header
part of 'task_icons.dart';

/// Sections of the icon picker, in picker order (docs/10 §3).
enum TaskIconCategory {
${cats.join(',\n')};
}

/// Every task icon, in picker order: by [category], then by English name.
/// [key] is the persisted `icon_key` (docs/05-data-model.md).
///
/// [circle] (the column default) is the "no icon yet" state: the dot shows
/// its colour with no glyph. Stored keys outside this set stay valid data
/// (see `domain/entities/icon_keys.dart`).
enum TaskIcon {
${icons.join(',\n')};

  const TaskIcon(this.key, this.category, this.glyph);

  /// Persisted `icon_key` value.
  final String key;

  /// The picker section this icon is listed under.
  final TaskIconCategory category;

  /// The glyph to draw, or null for [circle] (a plain dot).
  final DotGlyph? glyph;

  /// Icon for new tasks and unknown keys (the `icon_key` column default).
  static const fallback = TaskIcon.${lib.plain.id};

  /// The icons the picker offers (everything but [circle]), in order.
  static List<TaskIcon> get picker => _picker;

  /// Parses a stored `icon_key`. Retired keys map to their nearest icon,
  /// anything else to [fallback].
  static TaskIcon fromKey(String? key) => _fromKey(key);
}

/// Retired keys still found in stored data, and the icon each now shows.
const _legacy = <String, TaskIcon>{
${legacy.join('\n')}
};
''';
}

/// Renders the localized-name lookups for the picker and screen readers.
String renderTaskIconNames(IconLibrary lib) {
  final icons = [
    ...lib.icons,
    lib.plain,
  ].map((i) => '  TaskIcon.${i.id} => l10n.${i.arbKey},');
  final cats = lib.categories.map(
    (c) => '  TaskIconCategory.${c.id} => l10n.${c.arbKey},',
  );
  return '''
$_header
import 'package:dottoday/core/l10n/l10n.dart';
import 'package:dottoday/core/theme/dot_theme.dart';

/// Localised name of a task icon, for screen readers, search and the picker.
String taskIconName(AppLocalizations l10n, TaskIcon icon) => switch (icon) {
${icons.join('\n')}
};

/// Localised title of an icon picker section.
String taskIconCategoryName(
  AppLocalizations l10n,
  TaskIconCategory category,
) => switch (category) {
${cats.join('\n')}
};
''';
}

/// Replaces every `taskIcon*` entry of an ARB file with the library's, at
/// the end of the file. Other keys keep their text and layout byte for
/// byte; generated entries are one line each so they can be found again.
String mergeArb(String arb, IconLibrary lib, String lang) {
  final lines = const LineSplitter()
      .convert(arb)
      .where((l) => !RegExp(r'^  "@?taskIcon').hasMatch(l))
      .toList();
  final close = lines.lastIndexOf('}');
  final body = lines.sublist(0, close);
  final last = body.lastIndexWhere((l) => l.trim().isNotEmpty);
  if (!body[last].endsWith(',') && !body[last].endsWith('{')) {
    body[last] = '${body[last]},';
  }
  final entries = <String>[];
  void add(String key, Map<String, String> names, String description) {
    entries.add('  "$key": ${jsonEncode(names[lang])},');
    if (lang == 'en') {
      entries.add('  "@$key": {"description": ${jsonEncode(description)}},');
    }
  }

  for (final c in lib.categories) {
    add(c.arbKey, c.names, _arbCategoryDescription);
  }
  for (final i in [...lib.icons, lib.plain]) {
    add(i.arbKey, i.names, _arbDescription);
  }
  entries.last = entries.last.substring(0, entries.last.length - 1);
  return '${[...body.sublist(0, last + 1), ...entries, '}'].join('\n')}\n';
}

/// The decoded icon JSON. Throws [FormatException] when malformed.
final class IconLibrary {
  IconLibrary(this.categories, this.icons, this.plain, this.legacy);

  factory IconLibrary.parse(Object? json) {
    if (json is! Map<String, Object?>) throw const FormatException('root');
    final cats = [
      for (final c in json['categories']! as List)
        IconCategory((c as Map)['key'] as String, _names(c['name'])),
    ];
    final catKeys = cats.map((c) => c.key).toSet();
    final icons = [
      for (final i in json['icons']! as List) IconEntry.parse(i, catKeys),
    ];
    final plainJson = json['plain']! as Map;
    final plain = IconEntry(
      plainJson['key'] as String,
      _names(plainJson['name']),
      cats.first.key,
      '',
    );
    final byKey = {
      for (final i in [...icons, plain]) i.key: i,
    };
    if (byKey.length != icons.length + 1) {
      throw const FormatException('duplicate icon key');
    }
    // A retired key that is now a real icon resolves to that icon first, so
    // its legacy entry would be dead: drop it.
    final legacy = <String, String>{
      for (final MapEntry(:key, :value) in (json['legacy']! as Map).entries)
        if (!byKey.containsKey(key))
          key as String:
              (byKey[value] ?? (throw FormatException('legacy target $value')))
                  .id,
    };
    return IconLibrary(cats, icons, plain, legacy);
  }

  final List<IconCategory> categories;
  final List<IconEntry> icons;

  /// The "no icon" dot (`circle`): named, never in the picker.
  final IconEntry plain;
  final Map<String, String> legacy;
}

final class IconCategory {
  IconCategory(this.key, this.names);

  final String key;
  final Map<String, String> names;

  String get id => _camel(key);
  String get arbKey => 'taskIconCategory${_pascal(key)}';
}

final class IconEntry {
  IconEntry(this.key, this.names, this.category, this.d);

  factory IconEntry.parse(Object? json, Set<String> categories) {
    final m = json! as Map;
    final key = m['key'] as String;
    if (!RegExp(r'^[a-z][a-z0-9_]{0,47}$').hasMatch(key)) {
      throw FormatException('icon_key shape: $key');
    }
    final category = m['category'] as String;
    if (!categories.contains(category)) {
      throw FormatException('$key: unknown category $category');
    }
    final d = m['d'] as String;
    if (d.contains("'") || d.contains(r'$') || d.isEmpty) {
      throw FormatException('$key: bad path data');
    }
    return IconEntry(key, _names(m['name']), category, d);
  }

  final String key;
  final Map<String, String> names;
  final String category;
  final String d;

  /// Dart identifier: camelCase, suffixed where it would clash with a
  /// keyword or an `Enum`/`TaskIcon` member.
  String get id {
    final c = _camel(key);
    return _reserved.contains(c) ? '${c}Icon' : c;
  }

  String get arbKey => 'taskIcon${_pascal(key)}';
}

Map<String, String> _names(Object? json) {
  final m = (json! as Map).cast<String, String>();
  for (final lang in languages) {
    if ((m[lang] ?? '').trim().isEmpty) {
      throw FormatException('missing $lang name in $m');
    }
  }
  return m;
}

String _pascal(String key) => key
    .split('_')
    .map((w) => w.isEmpty ? '' : '${w[0].toUpperCase()}${w.substring(1)}')
    .join();

String _camel(String key) {
  final p = _pascal(key);
  final id = '${p[0].toLowerCase()}${p.substring(1)}';
  return RegExp('^[0-9]').hasMatch(id) ? 'i$id' : id;
}

const _reserved = {
  'assert', 'break', 'case', 'catch', 'class', 'const', 'continue', //
  'default', 'do', 'else', 'enum', 'extends', 'false', 'final', 'finally',
  'for', 'if', 'in', 'is', 'new', 'null', 'rethrow', 'return', 'super',
  'switch', 'this', 'throw', 'true', 'try', 'var', 'void', 'while', 'with',
  // Members of Enum and TaskIcon.
  'index', 'name', 'values', 'key', 'category', 'glyph', 'fallback',
  'picker', 'fromKey', 'hashCode', 'runtimeType', 'toString',
};
