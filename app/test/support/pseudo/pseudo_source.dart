/// Builds `pseudo_localizations.g.dart` from gen-l10n's abstract
/// `AppLocalizations`: one override per message that runs the English text
/// through `pseudo()`. A Dart class rather than a pseudo ARB keeps the
/// pseudo locale out of the shipped app's `supportedLocales`.
///
/// Regenerate: `dart run test/support/pseudo/write_pseudo.dart` (from app/).
String pseudoLocalizationsSource(String abstractSource) {
  final declaration = RegExp(
    r'^  String (get )?(\w+)(?:\(([^)]*)\))?;$',
    multiLine: true,
  );
  final out = StringBuffer(_header);
  for (final m in declaration.allMatches(abstractSource)) {
    final name = m.group(2)!;
    final params = m.group(3);
    if (m.group(1) != null || params == null) {
      out.writeln('  @override');
      out.writeln('  String get $name => pseudo(super.$name);');
    } else {
      final args = params
          .split(',')
          .map((p) => p.trim().split(' ').last)
          .join(', ');
      out.writeln('  @override');
      out.writeln('  String $name($params) => pseudo(super.$name($args));');
    }
    out.writeln();
  }
  out.writeln('}');
  return out.toString();
}

