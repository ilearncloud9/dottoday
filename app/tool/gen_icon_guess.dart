// Generates the icon guesser's index (lib/domain/icon_guess/) from
// assets/design/task_icon_keywords.json and the icon names in
// assets/design/task_icons.json: which typed words pick which icon, and
// the colour each icon's category suggests.
//
// Run from app/:  dart run tool/gen_icon_guess.dart
// test/domain/icon_guess/icon_guess_index_test.dart fails when stale.
import 'dart:convert';
import 'dart:io';

import 'package:dottoday/domain/entities/task_color_keys.gen.dart';
import 'package:dottoday/domain/icon_guess/icon_guess_text.dart';

import 'gen_task_icons.dart' as icons;

const keywordsPath = 'assets/design/task_icon_keywords.json';
const outputPath = 'lib/domain/icon_guess/icon_guess_index.gen.dart';

Future<void> main() async {
  final source = renderIconGuessIndex(
    icons.IconLibrary.parse(
      jsonDecode(await File(icons.inputPath).readAsString()),
    ),
    jsonDecode(await File(keywordsPath).readAsString()),
  );
  await icons.writeFormatted(source, outputPath);
  stdout.writeln('Wrote $outputPath');
}

/// Renders the index. Throws [FormatException] on an unknown icon,
/// category or colour, a missing language, or a strong term claimed by
/// two icons in one language.
String renderIconGuessIndex(icons.IconLibrary lib, Object? keywordsJson) {
  final k = _Keywords.parse(keywordsJson, lib);
  final strong = <String, Map<String, String>>{};
  final weak = <String, Map<String, String>>{};
  var maxWords = 1;
  for (final lang in icons.languages) {
    final s = strong[lang] = {};
    final w = weak[lang] = {};
    for (final MapEntry(key: icon, value: terms) in k.terms.entries) {
      for (final raw in terms[lang]!) {
        final isWeak = raw.startsWith('~');
        final term = guessKey(isWeak ? raw.substring(1) : raw);
        if (term.isEmpty) throw FormatException('$icon/$lang: empty term');
        final into = isWeak ? w : s;
        final owner = into[term];
        if (owner != null && owner != icon) {
          throw FormatException('$lang "$term": both $owner and $icon');
        }
        into[term] = icon;
      }
    }
    // Names match too (first icon wins a shared name), below any keyword.
    for (final i in lib.icons.where(k.matchesName)) {
      final term = guessKey(i.names[lang]!);
      if (term.isEmpty || w.containsKey(term)) continue;
      s.putIfAbsent(term, () => i.key);
    }
    for (final term in [...s.keys, ...w.keys]) {
      final n = term.split(' ').length;
      if (n > maxWords) maxWords = n;
    }
  }
  final used = {
    for (final m in [...strong.values, ...weak.values]) ...m.values,
  };
  final category = {for (final i in lib.icons) i.key: i.category};
  final colors = {
    for (final icon in used.toList()..sort()) icon: ?k.colors[category[icon]],
  };
  return '''
// GENERATED by tool/gen_icon_guess.dart from $keywordsPath
// and ${icons.inputPath}. Do not edit by hand; edit the JSON and re-run.

/// Longest term, in words.
const iconGuessMaxWords = $maxWords;

/// Folded term (see `guessKey`) → icon key, per language code.
const iconGuessStrong = <String, Map<String, String>>{
${_maps(strong)}
};

/// Generic verbs ("buy", "clean"): used only when no strong term matches.
const iconGuessWeak = <String, Map<String, String>>{
${_maps(weak)}
};

/// The colour an icon's category suggests; absent for no suggestion.
const iconGuessColors = <String, String>{
${colors.entries.map((e) => "  '${e.key}': '${e.value}',").join('\n')}
};
''';
}

String _maps(Map<String, Map<String, String>> byLang) => [
  for (final MapEntry(key: lang, value: terms) in byLang.entries)
    "  '$lang': {\n${[for (final t in terms.keys.toList()..sort()) "    '$t': '${terms[t]}',"].join('\n')}\n  },",
].join('\n');

final class _Keywords {
  _Keywords(this.terms, this.colors, this.skipNames, this.skipCategories);

  factory _Keywords.parse(Object? json, icons.IconLibrary lib) {
    if (json is! Map<String, Object?>) throw const FormatException('root');
    final known = {for (final i in lib.icons) i.key};
    final categories = {for (final c in lib.categories) c.key};
    final colors = (json['colors']! as Map).cast<String, String>();
    for (final MapEntry(:key, :value) in colors.entries) {
      if (!categories.contains(key)) throw FormatException('category $key');
      if (!taskColorKeys.contains(value)) {
        throw FormatException('colour $value');
      }
    }
    final skipNames = (json['skipNames']! as List).cast<String>().toSet();
    final skipCats = (json['skipNameCategories']! as List)
        .cast<String>()
        .toSet();
    for (final s in skipNames.where((s) => !known.contains(s))) {
      throw FormatException('skipNames: unknown icon $s');
    }
    final terms = <String, Map<String, List<String>>>{};
    for (final MapEntry(:key, :value)
        in (json['keywords']! as Map<String, Object?>).entries) {
      if (!known.contains(key)) throw FormatException('unknown icon $key');
      final byLang = (value! as Map).map(
        (l, t) => MapEntry(l as String, (t as List).cast<String>()),
      );
      for (final lang in icons.languages) {
        if (byLang[lang]?.isNotEmpty != true) {
          throw FormatException('$key: no $lang terms');
        }
      }
      terms[key] = byLang;
    }
    return _Keywords(terms, colors, skipNames, skipCats);
  }

  final Map<String, Map<String, List<String>>> terms;
  final Map<String, String> colors;
  final Set<String> skipNames;
  final Set<String> skipCategories;

  bool matchesName(icons.IconEntry i) =>
      !skipNames.contains(i.key) && !skipCategories.contains(i.category);
}
