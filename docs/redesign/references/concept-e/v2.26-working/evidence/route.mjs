import { createRequire } from 'module';
const require = createRequire('/Users/ops/Documents/dottoday/tool/a11y/package.json');
const { chromium } = require('playwright-core');
const exe = '/Users/ops/Library/Caches/ms-playwright/chromium_headless_shell-1248/chrome-headless-shell-mac-arm64/chrome-headless-shell';
const base = process.argv[2];
const b = await chromium.launch({ executablePath: exe });
const p = await b.newPage();
const state = async () => { await p.waitForTimeout(1500); const t = await p.evaluate(() => [...document.querySelectorAll('flt-semantics')].map(e => e.textContent || e.getAttribute('aria-label') || '').find(x => x.includes('VIEW=')) || '?'); return `${new URL(p.url()).hash}  |  ${t}`; };
const click = async (label) => { await p.evaluate((l) => { const el=[...document.querySelectorAll('flt-semantics')].find(e => (e.textContent||'').trim()===l); el.click(); }, label); };
const log = (k, v) => console.log(k.padEnd(34), v);
await p.goto(base + '/#/today'); log('1 open /#/today', await state());
await click('open t1'); log('2 tap open t1 (push)', await state());
await p.reload(); log('3 refresh', await state());
await p.goBack(); log('4 Back', await state());
await p.goForward(); log('5 Forward', await state());
await click('close'); log('6 close (go /today)', await state());
await p.goto(base + '/#/task/t9'); log('7 open link /#/task/t9', await state());
await p.goBack(); log('8 Back after link', await state());
await p.goto(base + '/#/day/2026-11-04?task=t2'); log('9 open /#/day/..?task=t2', await state());
await p.reload(); log('10 refresh', await state());
