// Generates the pure-Dart lib/domain/notifications/sound_catalogue.gen.dart
// from assets/sounds/manifest.json (docs/12-sounds.md §3, §5), so domain
// code can resolve sound ids without reading an asset.
//
// Run from app/:  dart run tool/gen_sound_catalogue.dart
// test/domain/notifications/sound_catalogue_test.dart fails when stale.
import 'dart:convert';
import 'dart:io';

import 'gen_task_palette.dart' show writeFormatted;

const inputPath = 'assets/sounds/manifest.json';
// Not `.g.dart`: `build_runner build -d` deletes `.g.dart` parts it did not
// generate (CI codegen step).
const outputPath = 'lib/domain/notifications/sound_catalogue.gen.dart';

/// Localised names (data layer: domain can't import l10n). Each id's ARB
/// key is [arbKeyFor]; every key must exist in app_en.arb.
const namesOutputPath = 'lib/data/notifications/sound_names.gen.dart';

/// The credited sources (docs/12 §1): the Sounds footer and the licences
/// notice are rendered from these, so a new source can't ship uncredited.
const creditsOutputPath = 'lib/data/notifications/sound_credits.gen.dart';

Future<void> main() async {
  final json = jsonDecode(await File(inputPath).readAsString());
  await writeFormatted(renderSoundCatalogue(json), outputPath);
  await writeFormatted(renderSoundNames(json), namesOutputPath);
  await writeFormatted(renderSoundCredits(json), creditsOutputPath);
  stdout.writeln('Wrote $outputPath, $namesOutputPath, $creditsOutputPath');
}

/// SPDX id → how the credit line says it (docs/12 §1).
const licenseLabels = {'CC-BY-4.0': 'CC BY 4.0', 'CC0-1.0': 'CC0 1.0'};

/// The manifest's credited sources as `(name, url, licence label, notice)`.
/// Throws [FormatException] on a malformed source or an unknown licence.
List<(String, String, String, String)> creditEntries(Object? json) {
  if (json case {'sources': final Map<String, Object?> sources}) {
    return [
      for (final s in sources.values)
        if (s case {'credit': true})
          if (s case {
            'name': final String name,
            'url': final String url,
            'license': final String license,
            'notice': final String notice,
          } when licenseLabels.containsKey(license))
            (name, url, licenseLabels[license]!, notice)
          else
            throw FormatException('Bad credited source: $s'),
    ];
  }
  throw const FormatException('Manifest has no sources');
}

/// The generated `soundCreditSources` library's source.
String renderSoundCredits(Object? json) {
  // A single-quoted Dart string (the lints' style) with \, ' and $ escaped.
  String quoted(String s) =>
      "'${s.replaceAll(r'\', r'\\').replaceAll("'", r"\'").replaceAll(r'$', r'\$')}'";
  final rows = creditEntries(json).map(
    (e) =>
        '  (name: ${quoted(e.$1)}, url: ${quoted(e.$2)}, '
        'license: ${quoted(e.$3)}, notice: ${quoted(e.$4)}),',
  );
  return '''
// GENERATED by tool/gen_sound_catalogue.dart from $inputPath.
// Do not edit by hand; edit the manifest and re-run the generator.

/// Every credited sound source (docs/12 §1): the Sounds footer names each
/// one with its licence, and About › Licences shows each notice.
const soundCreditSources =
    <({String name, String url, String license, String notice})>[
${rows.join('\n')}
];
''';
}

/// Every manifest sound as `(id, category, file)`, in manifest order.
/// Throws [FormatException] on a malformed manifest.
List<(String, String, String)> catalogueEntries(Object? json) {
  if (json case {'sounds': final List<Object?> sounds}) {
    return [
      for (final s in sounds)
        if (s case {
          'id': final String id,
          'category': final String category,
          'file': final String file,
        })
          (id, category, file)
        else
          throw FormatException('Bad sound entry: $s'),
    ];
  }
  throw const FormatException('Manifest has no sounds list');
}

/// The generated library's source.
String renderSoundCatalogue(Object? json) {
  final rows = catalogueEntries(
    json,
  ).map((e) => "  (id: '${e.$1}', category: '${e.$2}', file: '${e.$3}'),");
  return '''
// GENERATED by tool/gen_sound_catalogue.dart from $inputPath.
// Do not edit by hand; edit the manifest and re-run the generator.

/// Every bundled sound, in manifest (picker) order (docs/12 §2).
/// `category` is a `SoundCategory` name; `file` the base file name.
const soundCatalogueEntries = <({String id, String category, String file})>[
${rows.join('\n')}
];
''';
}

/// The ARB key of a sound's name: `sound` + the id's parts in PascalCase
/// (`quiet.slip` → `soundQuietSlip`, `dot` → `soundDot`).
String arbKeyFor(String id) =>
    'sound${[for (final p in id.split(RegExp('[._]'))) p[0].toUpperCase() + p.substring(1)].join()}';

/// The generated `soundDisplayName` library's source.
String renderSoundNames(Object? json) {
  final cases = catalogueEntries(
    json,
  ).map((e) => "  '${e.$1}' => l10n.${arbKeyFor(e.$1)},");
  return '''
// GENERATED by tool/gen_sound_catalogue.dart from $inputPath.
// Do not edit by hand; edit the manifest and re-run the generator.

import 'package:dottoday/core/l10n/l10n.dart';
import 'package:dottoday/domain/notifications/sound_catalogue.dart';

/// [sound]'s name in the user's language, for pickers, Android channel
/// names and the health panel (docs/12 §5: names live in ARB).
String soundDisplayName(AppLocalizations l10n, CatalogueSound sound) =>
    switch (sound.id) {
${cases.join('\n')}
      _ => sound.id,
    };
''';
}
