// Generates lib/core/theme/task_palette.gen.dart and the pure-Dart
// lib/domain/entities/task_color_keys.gen.dart from
// assets/design/palette.json (docs/10-ui-concept-a.md §2.1, plan M3a.1).
//
// Run from app/:  dart run tool/gen_task_palette.dart
// test/core/theme/task_palette_test.dart fails when the output is stale.
import 'dart:convert';
import 'dart:io';

const inputPath = 'assets/design/palette.json';
// Not `.g.dart`: `build_runner build -d` deletes `.g.dart` parts it did not
// generate (CI codegen step).
const outputPath = 'lib/core/theme/task_palette.gen.dart';
// `domain` cannot import `core/theme` (Flutter), so the allowed `color_key`
// and accent sets are emitted separately for validation (docs/05).
const keysOutputPath = 'lib/domain/entities/task_color_keys.gen.dart';

const _header =
    '// GENERATED by tool/gen_task_palette.dart from $inputPath.\n'
    '// Do not edit by hand; edit the JSON and re-run the generator.\n';

Future<void> main() async {
  final json = jsonDecode(await File(inputPath).readAsString());
  await writeFormatted(renderTaskPalette(json), outputPath);
  await writeFormatted(renderTaskColorKeys(json), keysOutputPath);
  stdout.writeln('Wrote $outputPath and $keysOutputPath');
}

/// Writes [source] to [path] and runs `dart format` on it, so the committed
/// file is byte-identical to what CI's format check expects.
Future<void> writeFormatted(String source, String path) async {
  await File(path).writeAsString(source);
  final result = await Process.run('dart', ['format', path]);
  if (result.exitCode != 0) {
    throw ProcessException('dart', ['format', path], '${result.stderr}');
  }
}

/// Renders the `part` file for `task_palette.dart` from decoded palette
/// JSON. Throws [FormatException] on a malformed palette.
String renderTaskPalette(Object? json) {
  final p = _Palette.parse(json);
  final colors = p.colors.map((c) => '  ${c.key}(${_color(c.hex)})');
  final accents = p.accents.map(
    (a) => '  ${a.key}(light: ${_color(a.light)}, dark: ${_color(a.dark)})',
  );
  final legacy = p.legacy.entries.map(
    (e) => "  '${e.key}': TaskColor.${e.value},",
  );
  return '''
$_header
part of 'task_palette.dart';

/// The 9 task colours in picker order (docs/10 §2.1); identical in both
/// themes. [key] is the persisted `color_key` (docs/05-data-model.md).
enum TaskColor {
${colors.join(',\n')};

  const TaskColor(this.color);

  /// The colour of the dot, segment and chip, before any alpha.
  final Color color;

  /// Colour for new tasks and unknown keys; matches the column default.
  static const fallback = TaskColor.${p.fallback};

  static final _byKey = values.asNameMap();

  /// Persisted `color_key` value.
  String get key => name;

  /// Parses a stored `color_key`. Keys of the retired 12-colour palette map
  /// to their nearest colour, anything else to [fallback], so data from an
  /// older or newer app never breaks rendering.
  static TaskColor fromKey(String? key) =>
      _byKey[key] ?? _legacy[key] ?? fallback;
}

const _legacy = <String, TaskColor>{
${legacy.join('\n')}
};

/// User-selectable accent (Settings › Look, docs/10 §2.1). [key] is the
/// persisted `settings.accent`.
enum DotAccent {
${accents.join(',\n')};

  const DotAccent({required this.light, required this.dark});

  final Color light;
  final Color dark;

  /// Accent for new profiles and unknown keys.
  static const fallback = DotAccent.${p.defaultAccent};

  static final _byKey = values.asNameMap();

  /// Persisted `settings.accent` value.
  String get key => name;

  /// Parses a stored accent, falling back to [fallback].
  static DotAccent fromKey(String? key) => _byKey[key] ?? fallback;
}
''';
}

/// Renders the pure-Dart key sets (no Flutter import) from decoded palette
/// JSON. Throws [FormatException] on a malformed palette.
String renderTaskColorKeys(Object? json) {
  final p = _Palette.parse(json);
  String quoted(Iterable<String> keys) => keys.map((k) => "'$k'").join(', ');
  return '''
$_header
/// `color_key` values the app writes, in picker order (docs/10 §2.1,
/// docs/05 "Validation"). Mirrors `TaskColor` without importing Flutter.
const taskColorKeys = <String>[${quoted(p.colors.map((c) => c.key))},];

/// Retired keys still accepted on read and sync (ADR-0007); the UI draws
/// them as their mapped colour and never writes them.
const legacyTaskColorKeys = <String>[${quoted(p.legacy.keys)},];

/// `color_key` for new tasks; matches the column default.
const defaultTaskColorKey = '${p.fallback}';

/// Allowed `settings.accent` values. Mirrors `DotAccent`.
const accentKeys = <String>[${quoted(p.accents.map((a) => a.key))},];

/// `settings.accent` for new profiles.
const defaultAccentKey = '${p.defaultAccent}';
''';
}

String _color(String hex) => 'Color(0xFF${hex.substring(1).toUpperCase()})';

Map<String, Object?> _map(Object? value, String where) {
  if (value is Map<String, Object?>) return value;
  throw FormatException('$where must be an object');
}

List<Object?> _list(Object? value, String where) {
  if (value is List<Object?> && value.isNotEmpty) return value;
  throw FormatException('$where must be a non-empty list');
}

final _hex = RegExp(r'^#[0-9A-Fa-f]{6}$');
final _keyPattern = RegExp(r'^[a-z]+$');

String _hexOf(Object? value, String where) {
  if (value is String && _hex.hasMatch(value)) return value;
  throw FormatException('$where must be "#RRGGBB", got $value');
}

String _keyOf(Object? value, String where) {
  if (value is String && _keyPattern.hasMatch(value)) return value;
  throw FormatException('$where must be lowercase letters, got $value');
}

final class _Palette {
  _Palette._(
    this.colors,
    this.fallback,
    this.legacy,
    this.accents,
    this.defaultAccent,
  );

  factory _Palette.parse(Object? json) {
    final doc = _map(json, 'root');
    final colors = [
      for (final c in _list(doc['colors'], 'colors')) _Color.parse(c),
    ];
    final keys = _unique(colors.map((c) => c.key), 'colour');
    final accents = [
      for (final a in _list(doc['accents'], 'accents')) _Accent.parse(a),
    ];
    final accentKeys = _unique(accents.map((a) => a.key), 'accent');
    final legacy = <String, String>{};
    for (final MapEntry(:key, :value) in _map(
      doc['legacy'],
      'legacy',
    ).entries) {
      final target = _keyOf(value, 'legacy.$key');
      if (keys.contains(_keyOf(key, 'legacy key')) || !keys.contains(target)) {
        throw FormatException('legacy $key → $target must map old → current');
      }
      legacy[key] = target;
    }
    return _Palette._(
      colors,
      _member(doc['default'], keys, 'default'),
      legacy,
      accents,
      _member(doc['defaultAccent'], accentKeys, 'defaultAccent'),
    );
  }

  final List<_Color> colors;
  final String fallback;
  final Map<String, String> legacy;
  final List<_Accent> accents;
  final String defaultAccent;

  static Set<String> _unique(Iterable<String> keys, String what) {
    final set = keys.toSet();
    if (set.length != keys.length) {
      throw FormatException('duplicate $what keys in $keys');
    }
    return set;
  }

  static String _member(Object? value, Set<String> keys, String where) {
    if (value is String && keys.contains(value)) return value;
    throw FormatException('"$where" must be one of $keys');
  }
}

final class _Color {
  _Color.parse(Object? json)
    : key = _keyOf(_map(json, 'colour')['key'], 'colour key'),
      hex = _hexOf(_map(json, 'colour')['hex'], 'colour hex');

  final String key;
  final String hex;
}

final class _Accent {
  _Accent.parse(Object? json)
    : key = _keyOf(_map(json, 'accent')['key'], 'accent key'),
      light = _hexOf(_map(json, 'accent')['light'], 'accent light'),
      dark = _hexOf(_map(json, 'accent')['dark'], 'accent dark');

  final String key;
  final String light;
  final String dark;
}
